static void framebuffer_clear_staged_blit(void) {
    staged_blit = (framebuffer_staged_blit_t){0};
}

static bool framebuffer_staged_blit_matches(int owner_pid,
                                             uint32_t owner_generation,
                                             uint32_t serial) {
    return staged_blit.active && staged_blit.owner_pid == owner_pid &&
           staged_blit.owner_generation == owner_generation &&
           (serial == 0U || staged_blit.serial == serial);
}

static void framebuffer_apply_staged_blit(int owner_pid,
                                           uint32_t owner_generation,
                                           uint32_t serial) {
    if (!framebuffer_staged_blit_matches(
            owner_pid, owner_generation, serial)) return;
    for (uint32_t row = 0U; row < staged_blit.height; ++row) {
        uint8_t *destination =
            fb_address + (staged_blit.destination_y + row) * fb_pitch +
            staged_blit.destination_x * fb_bytes_per_pixel;
        memcpy(destination,
               framebuffer_staged_blit + row * staged_blit.row_bytes,
               staged_blit.row_bytes);
    }
    framebuffer_clear_staged_blit();
}

static void framebuffer_scanout_fence(void) {
    if (fb_scanout_write_combining)
        __asm__ __volatile__("sfence" : : : "memory");
}

static void framebuffer_copy_to_scanout(
    const uint8_t *source, volatile uint8_t *destination_bytes,
    uint32_t byte_count) {
    if (source == NULL || destination_bytes == NULL || byte_count == 0U)
        return;
    uint32_t words = byte_count / sizeof(uint32_t);
    const uint32_t *source_words = (const uint32_t*)source;
    volatile uint32_t *destination =
        (volatile uint32_t*)destination_bytes;
    if (words != 0U) {
        /* REP MOVSL produces sequential stores without using FPU/SIMD
         * state and remains the compatible uncached-aperture fallback. */
        __asm__ __volatile__("cld\n\trep movsl"
                             : "+S"(source_words), "+D"(destination),
                               "+c"(words)
                             : : "memory");
    }
    uint32_t copied = byte_count & ~(uint32_t)(sizeof(uint32_t) - 1U);
    source = (const uint8_t*)source_words;
    destination_bytes = (volatile uint8_t*)destination;
    for (uint32_t byte = copied; byte < byte_count; ++byte)
        *destination_bytes++ = *source++;
}

static void framebuffer_blit_rect(uint32_t x, uint32_t y,
                                  uint32_t width, uint32_t height) {
    if (!fb_address || !fb_scanout_address || width == 0U || height == 0U ||
        x >= fb_width || y >= fb_height)
        return;
    if (width > fb_width - x) width = fb_width - x;
    if (height > fb_height - y) height = fb_height - y;

    if (fb_shadow_enabled) {
        uint32_t row_bytes = width * fb_bytes_per_pixel;
        if (x == 0U && row_bytes == fb_pitch) {
            framebuffer_copy_to_scanout(
                fb_address + y * fb_pitch,
                fb_scanout_address + y * fb_pitch,
                row_bytes * height);
            return;
        }
        for (uint32_t row = 0U; row < height; ++row) {
            const uint8_t *source = fb_address + (y + row) * fb_pitch +
                                    x * fb_bytes_per_pixel;
            volatile uint8_t *destination_bytes =
                fb_scanout_address + (y + row) * fb_pitch +
                x * fb_bytes_per_pixel;
            if (fb_bytes_per_pixel == sizeof(uint32_t)) {
                framebuffer_copy_to_scanout(
                    source, destination_bytes, row_bytes);
            } else {
                for (uint32_t byte = 0U; byte < row_bytes; ++byte)
                    destination_bytes[byte] = source[byte];
            }
        }
    }
}

static void framebuffer_restore_shadow_rect(uint32_t x, uint32_t y,
                                            uint32_t width,
                                            uint32_t height) {
    if (!fb_shadow_enabled || !fb_address || !fb_scanout_address ||
        width == 0U || height == 0U || x >= fb_width || y >= fb_height)
        return;
    if (width > fb_width - x) width = fb_width - x;
    if (height > fb_height - y) height = fb_height - y;
    uint32_t row_bytes = width * fb_bytes_per_pixel;
    for (uint32_t row = 0U; row < height; ++row) {
        uint8_t *destination = fb_address + (y + row) * fb_pitch +
                               x * fb_bytes_per_pixel;
        const volatile uint8_t *source =
            fb_scanout_address + (y + row) * fb_pitch +
            x * fb_bytes_per_pixel;
        for (uint32_t byte = 0U; byte < row_bytes; ++byte)
            destination[byte] = source[byte];
    }
}

static void framebuffer_blit_damage_excluding(
        display_frame_rect_t damage,
        const display_frame_rect_t *excluded) {
    if (excluded == NULL) {
        framebuffer_blit_rect(
            damage.x, damage.y, damage.width, damage.height);
        return;
    }
    uint32_t damage_right = damage.x + damage.width;
    uint32_t damage_bottom = damage.y + damage.height;
    uint32_t excluded_right = excluded->x + excluded->width;
    uint32_t excluded_bottom = excluded->y + excluded->height;
    uint32_t left = damage.x > excluded->x ? damage.x : excluded->x;
    uint32_t top = damage.y > excluded->y ? damage.y : excluded->y;
    uint32_t right = damage_right < excluded_right
        ? damage_right : excluded_right;
    uint32_t bottom = damage_bottom < excluded_bottom
        ? damage_bottom : excluded_bottom;
    if (left >= right || top >= bottom) {
        framebuffer_blit_rect(
            damage.x, damage.y, damage.width, damage.height);
        return;
    }

    if (top > damage.y)
        framebuffer_blit_rect(
            damage.x, damage.y, damage.width, top - damage.y);
    if (bottom < damage_bottom)
        framebuffer_blit_rect(
            damage.x, bottom, damage.width, damage_bottom - bottom);
    if (left > damage.x)
        framebuffer_blit_rect(
            damage.x, top, left - damage.x, bottom - top);
    if (right < damage_right)
        framebuffer_blit_rect(
            right, top, damage_right - right, bottom - top);
}

static void framebuffer_publish_damage(
        const display_frame_rect_t *damage, uint32_t count,
        const display_frame_rect_t *accelerated) {
    if (damage == NULL || count > DISPLAY_FRAME_DAMAGE_CAPACITY) return;
    display_control_rect_t updates[DISPLAY_FRAME_DAMAGE_CAPACITY];
    for (uint32_t index = 0U; index < count; ++index) {
        framebuffer_blit_damage_excluding(damage[index], accelerated);
        updates[index] = (display_control_rect_t){
            .x = damage[index].x,
            .y = damage[index].y,
            .width = damage[index].width,
            .height = damage[index].height,
        };
    }
    /* The shadow never contains the software pointer.  Reapply its bounded
     * scanout overlay after scene pixels so a GUI frame cannot erase it and
     * no compositor-side hide/show presentations are needed. */
    framebuffer_overlay_pointer_for_damage(damage, count);
    framebuffer_scanout_fence();
    display_control_present_rects(updates, count);
}

static void framebuffer_publish_cursor_damage(
        const display_frame_rect_t *damage, uint32_t count,
        bool restore_old_pointer) {
    if (damage == NULL || count == 0U ||
        count > DISPLAY_FRAME_DAMAGE_CAPACITY) return;
    display_control_rect_t updates[DISPLAY_FRAME_DAMAGE_CAPACITY];
    if (restore_old_pointer) {
        framebuffer_blit_rect(damage[0].x, damage[0].y,
                              damage[0].width, damage[0].height);
    }
    framebuffer_overlay_pointer_for_damage(damage, count);
    for (uint32_t index = 0U; index < count; ++index) {
        updates[index] = (display_control_rect_t){
            .x = damage[index].x,
            .y = damage[index].y,
            .width = damage[index].width,
            .height = damage[index].height,
        };
    }
    framebuffer_scanout_fence();
    display_control_present_rects(updates, count);
}

static void framebuffer_present_damage(const display_frame_rect_t *damage,
                                       uint32_t count) {
    if (damage == NULL || count == 0U ||
        count > DISPLAY_FRAME_DAMAGE_CAPACITY) return;
    bool deferred = false;
    uint32_t flags = spinlock_acquire_irq(&frame_transaction_lock);
    for (uint32_t index = 0U; index < count; ++index)
        deferred |= display_frame_record_damage(
            &frame_transaction, damage[index]);
    bool transition_in_progress = frame_transaction.transitioning;
    spinlock_release_irq(&frame_transaction_lock, flags);
    if (deferred || transition_in_progress) return;
    framebuffer_publish_damage(damage, count, NULL);
}

static void framebuffer_present_cursor_damage(
        const display_frame_rect_t *damage, uint32_t count,
        bool restore_old_pointer) {
    if (damage == NULL || count == 0U ||
        count > DISPLAY_FRAME_DAMAGE_CAPACITY) return;
    bool deferred = false;
    uint32_t flags = spinlock_acquire_irq(&frame_transaction_lock);
    for (uint32_t index = 0U; index < count; ++index)
        deferred |= display_frame_record_damage(
            &frame_transaction, damage[index]);
    bool transition_in_progress = frame_transaction.transitioning;
    spinlock_release_irq(&frame_transaction_lock, flags);
    if (deferred || transition_in_progress) return;
    framebuffer_publish_cursor_damage(
        damage, count, restore_old_pointer);
}

static void framebuffer_restore_damage(const display_frame_rect_t *damage,
                                       uint32_t count) {
    if (damage == NULL || count > DISPLAY_FRAME_DAMAGE_CAPACITY) return;
    for (uint32_t index = 0U; index < count; ++index)
        framebuffer_restore_shadow_rect(damage[index].x, damage[index].y,
                                        damage[index].width,
                                        damage[index].height);
}

static void framebuffer_finish_frame_transition(void) {
    uint32_t flags = spinlock_acquire_irq(&frame_transaction_lock);
    display_frame_finish_transition(&frame_transaction);
    spinlock_release_irq(&frame_transaction_lock, flags);
}

static int framebuffer_reap_expired_frame(uint64_t now_ms) {
    display_frame_rect_t damage[DISPLAY_FRAME_DAMAGE_CAPACITY];
    uint32_t damage_count = 0U;
    uint32_t flags = spinlock_acquire_irq(&frame_transaction_lock);
    int result = display_frame_prepare_expired(
        &frame_transaction, now_ms, damage, &damage_count);
    spinlock_release_irq(&frame_transaction_lock, flags);
    if (result == 1) {
        if (framebuffer_staged_blit_matches(
                frame_transaction.transition_owner_pid,
                frame_transaction.transition_owner_generation, 0U))
            framebuffer_clear_staged_blit();
        framebuffer_restore_damage(damage, damage_count);
        framebuffer_finish_frame_transition();
    }
    return result;
}

static void framebuffer_present_rect(uint32_t x, uint32_t y,
                                     uint32_t width, uint32_t height) {
    display_frame_rect_t rect = {x, y, width, height};
    framebuffer_present_damage(&rect, 1U);
}

int framebuffer_frame_begin(int owner_pid, uint32_t owner_generation,
                            uint64_t now_ms, uint32_t *serial_out) {
    if (!fb_address) return -19;
    if (!fb_shadow_enabled) return -95;
    (void)framebuffer_reap_expired_frame(now_ms);
    uint32_t flags = spinlock_acquire_irq(&frame_transaction_lock);
    int result = display_frame_begin(&frame_transaction, owner_pid,
                                     owner_generation, now_ms, serial_out);
    spinlock_release_irq(&frame_transaction_lock, flags);
    return result;
}

int framebuffer_frame_stage_blit(int owner_pid, uint32_t owner_generation,
                                 uint32_t serial, uint64_t now_ms,
                                 uint32_t source_x, uint32_t source_y,
                                 uint32_t destination_x,
                                 uint32_t destination_y,
                                 uint32_t width, uint32_t height) {
    if (!fb_shadow_enabled || !fb_address || fb_bytes_per_pixel == 0U)
        return -95;
    if (serial == 0U || width == 0U || height == 0U ||
        source_x >= fb_width || source_y >= fb_height ||
        destination_x >= fb_width || destination_y >= fb_height ||
        width > fb_width - source_x || height > fb_height - source_y ||
        width > fb_width - destination_x ||
        height > fb_height - destination_y)
        return -22;
    uint64_t row_bytes = (uint64_t)width * fb_bytes_per_pixel;
    uint64_t total_bytes = row_bytes * height;
    if (row_bytes == 0U || row_bytes > UINT32_MAX ||
        total_bytes > sizeof(framebuffer_staged_blit)) return -22;

    (void)framebuffer_reap_expired_frame(now_ms);
    uint32_t flags = spinlock_acquire_irq(&frame_transaction_lock);
    int result;
    if (!frame_transaction.active ||
        frame_transaction.owner_pid != owner_pid ||
        frame_transaction.owner_generation != owner_generation) {
        result = -13;
    } else if (frame_transaction.serial != serial) {
        result = -116;
    } else if (staged_blit.active) {
        result = -16;
    } else {
        result = display_frame_draw_enter(
            &frame_transaction, owner_pid, owner_generation, now_ms);
    }
    spinlock_release_irq(&frame_transaction_lock, flags);
    if (result != 0) return result;

    uint32_t bytes = (uint32_t)row_bytes;
    for (uint32_t row = 0U; row < height; ++row) {
        const uint8_t *source =
            fb_address + (source_y + row) * fb_pitch +
            source_x * fb_bytes_per_pixel;
        memcpy(framebuffer_staged_blit + row * bytes, source, bytes);
    }

    flags = spinlock_acquire_irq(&frame_transaction_lock);
    result = display_frame_draw_leave(
        &frame_transaction, owner_pid, owner_generation, now_ms);
    if (result == 0 && frame_transaction.active &&
        frame_transaction.serial == serial) {
        staged_blit = (framebuffer_staged_blit_t){
            .owner_pid = owner_pid,
            .owner_generation = owner_generation,
            .serial = serial,
            .source_x = source_x,
            .source_y = source_y,
            .destination_x = destination_x,
            .destination_y = destination_y,
            .width = width,
            .height = height,
            .row_bytes = bytes,
            .active = true,
            .accelerated = false,
        };
        if (!display_frame_record_damage(
                &frame_transaction,
                (display_frame_rect_t){destination_x, destination_y,
                                       width, height})) {
            framebuffer_clear_staged_blit();
            result = -5;
        }
    }
    spinlock_release_irq(&frame_transaction_lock, flags);
    if (result == -110) (void)framebuffer_reap_expired_frame(now_ms);
    return result;
}

int framebuffer_frame_mark_accelerated(int owner_pid,
                                       uint32_t owner_generation,
                                       uint32_t serial) {
    if (serial == 0U || !display_control_acceleration_active())
        return -95;
    uint32_t flags = spinlock_acquire_irq(&frame_transaction_lock);
    int result = 0;
    if (!framebuffer_staged_blit_matches(
            owner_pid, owner_generation, serial) ||
        !frame_transaction.active || frame_transaction.serial != serial) {
        result = -116;
    } else {
        staged_blit.accelerated = true;
    }
    spinlock_release_irq(&frame_transaction_lock, flags);
    return result;
}

int framebuffer_frame_commit(int owner_pid, uint32_t owner_generation,
                             uint32_t serial, uint64_t now_ms) {
    display_frame_rect_t damage[DISPLAY_FRAME_DAMAGE_CAPACITY];
    uint32_t damage_count = 0U;
    uint32_t flags = spinlock_acquire_irq(&frame_transaction_lock);
    int result = display_frame_prepare_commit(
        &frame_transaction, owner_pid, owner_generation, serial, now_ms,
        damage, &damage_count);
    spinlock_release_irq(&frame_transaction_lock, flags);
    if (result == -110) (void)framebuffer_reap_expired_frame(now_ms);
    if (result != 0) return result;
    display_frame_rect_t accelerated;
    const display_frame_rect_t *accelerated_ptr = NULL;
    if (framebuffer_staged_blit_matches(
            owner_pid, owner_generation, serial) && staged_blit.accelerated) {
        accelerated = (display_frame_rect_t){
            staged_blit.destination_x, staged_blit.destination_y,
            staged_blit.width, staged_blit.height,
        };
        accelerated_ptr = &accelerated;
    }
    framebuffer_apply_staged_blit(owner_pid, owner_generation, serial);
    framebuffer_publish_damage(damage, damage_count, accelerated_ptr);
    framebuffer_finish_frame_transition();
    return 0;
}

int framebuffer_frame_cancel(int owner_pid, uint32_t owner_generation,
                             uint32_t serial) {
    display_frame_rect_t damage[DISPLAY_FRAME_DAMAGE_CAPACITY];
    uint32_t damage_count = 0U;
    uint32_t flags = spinlock_acquire_irq(&frame_transaction_lock);
    int result = display_frame_prepare_cancel(
        &frame_transaction, owner_pid, owner_generation, serial,
        damage, &damage_count);
    spinlock_release_irq(&frame_transaction_lock, flags);
    if (result != 0) return result;
    if (framebuffer_staged_blit_matches(
            owner_pid, owner_generation, serial))
        framebuffer_clear_staged_blit();
    framebuffer_restore_damage(damage, damage_count);
    framebuffer_finish_frame_transition();
    return 0;
}

int framebuffer_frame_draw_enter(int owner_pid, uint32_t owner_generation,
                                 uint64_t now_ms) {
    (void)framebuffer_reap_expired_frame(now_ms);
    uint32_t flags = spinlock_acquire_irq(&frame_transaction_lock);
    int result = display_frame_draw_enter(
        &frame_transaction, owner_pid, owner_generation, now_ms);
    spinlock_release_irq(&frame_transaction_lock, flags);
    return result;
}

int framebuffer_frame_draw_leave(int owner_pid, uint32_t owner_generation,
                                 uint64_t now_ms) {
    uint32_t flags = spinlock_acquire_irq(&frame_transaction_lock);
    int result = display_frame_draw_leave(
        &frame_transaction, owner_pid, owner_generation, now_ms);
    spinlock_release_irq(&frame_transaction_lock, flags);
    if (result == -110) (void)framebuffer_reap_expired_frame(now_ms);
    return result;
}

void framebuffer_frame_process_cleanup(int owner_pid,
                                       uint32_t owner_generation) {
    framebuffer_surface_buffer_process_cleanup(
        owner_pid, owner_generation);
    display_frame_rect_t damage[DISPLAY_FRAME_DAMAGE_CAPACITY];
    uint32_t damage_count = 0U;
    uint32_t action = 0U;
    uint32_t flags = spinlock_acquire_irq(&frame_transaction_lock);
    int result = display_frame_recover_transition(
        &frame_transaction, owner_pid, owner_generation,
        damage, &damage_count, &action);
    spinlock_release_irq(&frame_transaction_lock, flags);
    if (result == 1) {
        if (action == DISPLAY_FRAME_TRANSITION_PUBLISH) {
            framebuffer_apply_staged_blit(
                owner_pid, owner_generation, 0U);
            framebuffer_publish_damage(damage, damage_count, NULL);
        } else {
            if (framebuffer_staged_blit_matches(
                    owner_pid, owner_generation, 0U))
                framebuffer_clear_staged_blit();
            framebuffer_restore_damage(damage, damage_count);
        }
        framebuffer_finish_frame_transition();
        return;
    }

    damage_count = 0U;
    flags = spinlock_acquire_irq(&frame_transaction_lock);
    result = display_frame_prepare_cleanup(
        &frame_transaction, owner_pid, owner_generation,
        damage, &damage_count);
    spinlock_release_irq(&frame_transaction_lock, flags);
    if (result == 1) {
        if (framebuffer_staged_blit_matches(
                owner_pid, owner_generation, 0U))
            framebuffer_clear_staged_blit();
        framebuffer_restore_damage(damage, damage_count);
        framebuffer_finish_frame_transition();
    }
}

static void framebuffer_reset_frame_transaction(uint32_t width,
                                                uint32_t height) {
    uint32_t flags = spinlock_acquire_irq(&frame_transaction_lock);
    display_frame_transaction_init(&frame_transaction, width, height);
    framebuffer_clear_staged_blit();
    spinlock_release_irq(&frame_transaction_lock, flags);
}

// Initialize framebuffer
static void framebuffer_initialize(multiboot_framebuffer_info_t* fb_info,
                                   bool present_clear) {
    framebuffer_reset_frame_transaction(0U, 0U);
    fb_address = NULL;
    fb_scanout_address = NULL;
    fb_shadow_enabled = false;
    fb_scanout_write_combining = false;
    fb_width = fb_height = fb_pitch = 0;
    fb_bpp = fb_bytes_per_pixel = 0;
    fb_red_position = fb_red_size = 0;
    fb_green_position = fb_green_size = 0;
    fb_blue_position = fb_blue_size = 0;
    terminal_cols = terminal_rows = 0;
    pointer_visible = false;
    pointer_width = pointer_height = 0U;
    if (!fb_info || fb_info->framebuffer_addr == 0 ||
        fb_info->framebuffer_type != 1 ||
        fb_info->framebuffer_width < FONT_WIDTH ||
        fb_info->framebuffer_height < FONT_HEIGHT ||
        (fb_info->framebuffer_bpp != 8 && fb_info->framebuffer_bpp != 16 &&
         fb_info->framebuffer_bpp != 24 && fb_info->framebuffer_bpp != 32) ||
        !framebuffer_channel_valid(fb_info->red_field_position,
                                   fb_info->red_mask_size,
                                   fb_info->framebuffer_bpp) ||
        !framebuffer_channel_valid(fb_info->green_field_position,
                                   fb_info->green_mask_size,
                                   fb_info->framebuffer_bpp) ||
        !framebuffer_channel_valid(fb_info->blue_field_position,
                                   fb_info->blue_mask_size,
                                   fb_info->framebuffer_bpp)) return;

    uint64_t red_mask = framebuffer_channel_mask(fb_info->red_field_position,
                                                 fb_info->red_mask_size);
    uint64_t green_mask = framebuffer_channel_mask(fb_info->green_field_position,
                                                   fb_info->green_mask_size);
    uint64_t blue_mask = framebuffer_channel_mask(fb_info->blue_field_position,
                                                  fb_info->blue_mask_size);
    if ((red_mask & green_mask) || (red_mask & blue_mask) ||
        (green_mask & blue_mask)) return;

    uint8_t bytes_per_pixel = (uint8_t)(fb_info->framebuffer_bpp / 8u);
    if (fb_info->framebuffer_width > 0xFFFFFFFFu / bytes_per_pixel ||
        fb_info->framebuffer_pitch < fb_info->framebuffer_width * bytes_per_pixel) return;
    uint64_t framebuffer_size = (uint64_t)fb_info->framebuffer_pitch *
                                fb_info->framebuffer_height;
    if (framebuffer_size == 0 || framebuffer_size > 0x100000000ULL ||
        fb_info->framebuffer_addr > 0xFFFFFFFFULL ||
        fb_info->framebuffer_addr + framebuffer_size > 0x100000000ULL) return;

    void *mapping = map_kernel_write_combining(
        (uint32_t)fb_info->framebuffer_addr, (size_t)framebuffer_size);
    if (mapping != NULL) fb_scanout_write_combining = true;
    else mapping = map_kernel_mmio((uint32_t)fb_info->framebuffer_addr,
                                   (size_t)framebuffer_size);
    if (mapping == NULL) return;
    fb_scanout_address = (volatile uint8_t*)mapping;
    if (framebuffer_size <= FB_SHADOW_CAPACITY) {
        fb_address = framebuffer_shadow;
        fb_shadow_enabled = true;
    } else {
        fb_address = (uint8_t*)mapping;
    }
    fb_width = fb_info->framebuffer_width;
    fb_height = fb_info->framebuffer_height;
    fb_pitch = fb_info->framebuffer_pitch;
    fb_bpp = fb_info->framebuffer_bpp;
    fb_bytes_per_pixel = bytes_per_pixel;
    fb_red_position = fb_info->red_field_position;
    fb_red_size = fb_info->red_mask_size;
    fb_green_position = fb_info->green_field_position;
    fb_green_size = fb_info->green_mask_size;
    fb_blue_position = fb_info->blue_field_position;
    fb_blue_size = fb_info->blue_mask_size;
    terminal_cols = (int)(fb_width / FONT_WIDTH);
    terminal_rows = (int)(fb_height / FONT_HEIGHT);
    framebuffer_reset_frame_transaction(fb_width, fb_height);
    
    cursor_x = 0;
    cursor_y = 0;
    
    framebuffer_clear_internal(present_clear || !fb_shadow_enabled);
}

void framebuffer_init(multiboot_framebuffer_info_t* fb_info) {
    framebuffer_initialize(fb_info, true);
}

void framebuffer_init_runtime(multiboot_framebuffer_info_t* fb_info) {
    framebuffer_initialize(fb_info, false);
}

void framebuffer_shutdown(void) {
    framebuffer_reset_frame_transaction(0U, 0U);
    fb_address = NULL;
    fb_scanout_address = NULL;
    fb_shadow_enabled = false;
    fb_scanout_write_combining = false;
    fb_width = fb_height = fb_pitch = 0U;
    fb_bpp = fb_bytes_per_pixel = 0U;
    fb_red_position = fb_red_size = 0U;
    fb_green_position = fb_green_size = 0U;
    fb_blue_position = fb_blue_size = 0U;
    terminal_cols = terminal_rows = 0;
    cursor_x = cursor_y = 0;
    pointer_visible = false;
    pointer_width = pointer_height = 0U;
}

// Check if framebuffer is available
bool framebuffer_available() {
    return (fb_address != NULL);
}

static uint32_t framebuffer_scale_channel(uint8_t value, uint8_t bits) {
    if (bits == 8U) return value;
    uint64_t maximum = ((uint64_t)1u << bits) - 1u;
    return (uint32_t)(((uint64_t)value * maximum + 127u) / 255u);
}

static uint32_t framebuffer_native_color(uint32_t rgb) {
    uint8_t red = (uint8_t)(rgb >> 16);
    uint8_t green = (uint8_t)(rgb >> 8);
    uint8_t blue = (uint8_t)rgb;
    return
        (framebuffer_scale_channel(red, fb_red_size) << fb_red_position) |
        (framebuffer_scale_channel(green, fb_green_size) << fb_green_position) |
        (framebuffer_scale_channel(blue, fb_blue_size) << fb_blue_position);
}

static inline void framebuffer_store_native(uint8_t *pixel,
                                            uint32_t native_color) {
    if (fb_bytes_per_pixel == sizeof(uint32_t)) {
        if (fb_shadow_enabled)
            *(uint32_t*)pixel = native_color;
        else
            *(volatile uint32_t*)pixel = native_color;
        return;
    }
    for (uint8_t byte = 0; byte < fb_bytes_per_pixel; ++byte) {
        if (fb_shadow_enabled)
            pixel[byte] = (uint8_t)(native_color >> (byte * 8u));
        else
            ((volatile uint8_t*)pixel)[byte] =
                (uint8_t)(native_color >> (byte * 8u));
    }
}

static int framebuffer_pointer_shape_color(uint32_t x, uint32_t y) {
    if (x >= FB_POINTER_SHAPE_WIDTH || y >= FB_POINTER_SHAPE_HEIGHT)
        return -1;
    if (pointer_shape[y][x] == 'B') return 0;
    if (pointer_shape[y][x] == 'W') return 1;
    return -1;
}

static int framebuffer_pointer_color(uint32_t x, uint32_t y) {
    int color = framebuffer_pointer_shape_color(x, y);
    if (color >= 0) return color;
    /* A transparent pixel one step down/right from the opaque arrow becomes
     * the subtle shadow.  The result is 2, distinct from black and white. */
    if (x != 0U && y != 0U &&
        framebuffer_pointer_shape_color(x - 1U, y - 1U) >= 0)
        return 2;
    return -1;
}

static void framebuffer_store_scanout_native(volatile uint8_t *pixel,
                                             uint32_t native_color) {
    if (fb_bytes_per_pixel == sizeof(uint32_t)) {
        *(volatile uint32_t*)pixel = native_color;
        return;
    }
    for (uint8_t byte = 0U; byte < fb_bytes_per_pixel; ++byte)
        pixel[byte] = (uint8_t)(native_color >> (byte * 8U));
}

static void framebuffer_overlay_pointer_for_damage(
        const display_frame_rect_t *damage, uint32_t count) {
    if (!fb_shadow_enabled || !pointer_visible || damage == NULL ||
        count == 0U || fb_scanout_address == NULL) return;

    uint32_t pointer_right = (uint32_t)pointer_x + pointer_width;
    uint32_t pointer_bottom = (uint32_t)pointer_y + pointer_height;
    bool intersects = false;
    for (uint32_t index = 0U; index < count; ++index) {
        uint32_t damage_right = damage[index].x + damage[index].width;
        uint32_t damage_bottom = damage[index].y + damage[index].height;
        if (damage[index].x < pointer_right &&
            damage_right > (uint32_t)pointer_x &&
            damage[index].y < pointer_bottom &&
            damage_bottom > (uint32_t)pointer_y) {
            intersects = true;
            break;
        }
    }
    if (!intersects) return;

    uint32_t black = framebuffer_native_color(0x00000000U);
    uint32_t white = framebuffer_native_color(0x00FFFFFFU);
    uint32_t shadow = framebuffer_native_color(0x00606060U);
    for (uint32_t row = 0U; row < pointer_height; ++row) {
        for (uint32_t column = 0U; column < pointer_width; ++column) {
            int color = framebuffer_pointer_color(column, row);
            if (color < 0) continue;
            volatile uint8_t *pixel = fb_scanout_address +
                ((uint32_t)pointer_y + row) * fb_pitch +
                ((uint32_t)pointer_x + column) * fb_bytes_per_pixel;
            framebuffer_store_scanout_native(
                pixel, color == 0 ? black : (color == 1 ? white : shadow));
        }
    }
}

bool framebuffer_cursor_update(int32_t x, int32_t y, bool visible) {
    if (!fb_address || fb_bytes_per_pixel == 0U ||
        fb_bytes_per_pixel > FB_POINTER_MAX_BYTES) return false;
    if (pointer_visible && visible && x == pointer_x && y == pointer_y)
        return true;

    display_frame_rect_t damage[2];
    uint32_t damage_count = 0U;
    if (fb_shadow_enabled) {
        bool restore_old_pointer = pointer_visible;
        if (pointer_visible) {
            damage[damage_count++] = (display_frame_rect_t){
                (uint32_t)pointer_x, (uint32_t)pointer_y,
                pointer_width, pointer_height,
            };
        }
        pointer_visible = false;
        pointer_width = pointer_height = 0U;
        if (visible && x >= 0 && y >= 0 && x < (int32_t)fb_width &&
            y < (int32_t)fb_height) {
            uint32_t width = FB_POINTER_WIDTH;
            uint32_t height = FB_POINTER_HEIGHT;
            if ((uint32_t)x + width > fb_width)
                width = fb_width - (uint32_t)x;
            if ((uint32_t)y + height > fb_height)
                height = fb_height - (uint32_t)y;
            damage[damage_count++] = (display_frame_rect_t){
                (uint32_t)x, (uint32_t)y, width, height,
            };
            pointer_x = x;
            pointer_y = y;
            pointer_width = width;
            pointer_height = height;
            pointer_visible = true;
        }
        if (damage_count != 0U)
            framebuffer_present_cursor_damage(
                damage, damage_count, restore_old_pointer);
        return true;
    }

    if (pointer_visible) {
        damage[damage_count++] = (display_frame_rect_t){
            (uint32_t)pointer_x, (uint32_t)pointer_y,
            pointer_width, pointer_height,
        };
        for (uint32_t row = 0U; row < pointer_height; ++row) {
            for (uint32_t column = 0U; column < pointer_width; ++column) {
                uint8_t *pixel = fb_address +
                    ((uint32_t)pointer_y + row) * fb_pitch +
                    ((uint32_t)pointer_x + column) * fb_bytes_per_pixel;
                const uint8_t *saved = &pointer_saved[
                    (row * FB_POINTER_WIDTH + column) *
                    FB_POINTER_MAX_BYTES];
                for (uint8_t byte = 0U; byte < fb_bytes_per_pixel; ++byte)
                    pixel[byte] = saved[byte];
            }
        }
    }

    pointer_visible = false;
    pointer_width = pointer_height = 0U;
    if (visible && x >= 0 && y >= 0 && x < (int32_t)fb_width &&
        y < (int32_t)fb_height) {
        uint32_t width = FB_POINTER_WIDTH;
        uint32_t height = FB_POINTER_HEIGHT;
        if ((uint32_t)x + width > fb_width) width = fb_width - (uint32_t)x;
        if ((uint32_t)y + height > fb_height)
            height = fb_height - (uint32_t)y;
        damage[damage_count++] = (display_frame_rect_t){
            (uint32_t)x, (uint32_t)y, width, height,
        };
        uint32_t black = framebuffer_native_color(0x00000000U);
        uint32_t white = framebuffer_native_color(0x00FFFFFFU);
        uint32_t shadow = framebuffer_native_color(0x00606060U);
        for (uint32_t row = 0U; row < height; ++row) {
            for (uint32_t column = 0U; column < width; ++column) {
                uint8_t *pixel = fb_address + ((uint32_t)y + row) * fb_pitch +
                                 ((uint32_t)x + column) * fb_bytes_per_pixel;
                uint8_t *saved = &pointer_saved[
                    (row * FB_POINTER_WIDTH + column) *
                    FB_POINTER_MAX_BYTES];
                for (uint8_t byte = 0U; byte < fb_bytes_per_pixel; ++byte)
                    saved[byte] = pixel[byte];
                int color = framebuffer_pointer_color(column, row);
                if (color >= 0)
                    framebuffer_store_native(
                        pixel, color == 0 ? black
                                         : (color == 1 ? white : shadow));
            }
        }
        pointer_x = x;
        pointer_y = y;
        pointer_width = width;
        pointer_height = height;
        pointer_visible = true;
    }
    if (damage_count != 0U)
        framebuffer_present_damage(damage, damage_count);
    return true;
}

static void fb_draw_glyph_pixels(uint8_t glyph_index, int x, int y, uint32_t fg,
                                 uint32_t bg) {
    const uint8_t* glyph = &font_8x16[(size_t)glyph_index * FONT_HEIGHT];
    uint32_t native_foreground = framebuffer_native_color(fg);
    uint32_t native_background = framebuffer_native_color(bg);

    for (int row = 0; row < FONT_HEIGHT; row++) {
        int pixel_y = y + row;
        if (pixel_y < 0 || pixel_y >= (int)fb_height) continue;
        uint8_t line = glyph[row];
        for (int col = 0; col < FONT_WIDTH; col++) {
            int pixel_x = x + col;
            if (pixel_x < 0 || pixel_x >= (int)fb_width) continue;
            uint8_t *pixel = fb_address + (uint32_t)pixel_y * fb_pitch +
                             (uint32_t)pixel_x * fb_bytes_per_pixel;
            framebuffer_store_native(
                pixel, (line & (0x80 >> col))
                    ? native_foreground : native_background);
        }
    }
}

static void fb_draw_glyph_pixels_clipped(
    uint8_t glyph_index, int x, int y, uint32_t fg, uint32_t bg,
    int clip_left, int clip_top, int clip_right, int clip_bottom) {
    const uint8_t *glyph = &font_8x16[(size_t)glyph_index * FONT_HEIGHT];
    uint32_t native_foreground = framebuffer_native_color(fg);
    uint32_t native_background = framebuffer_native_color(bg);

    for (int row = 0; row < FONT_HEIGHT; ++row) {
        int pixel_y = y + row;
        if (pixel_y < clip_top || pixel_y >= clip_bottom) continue;
        uint8_t line = glyph[row];
        for (int column = 0; column < FONT_WIDTH; ++column) {
            int pixel_x = x + column;
            if (pixel_x < clip_left || pixel_x >= clip_right) continue;
            uint8_t *pixel = fb_address + (uint32_t)pixel_y * fb_pitch +
                             (uint32_t)pixel_x * fb_bytes_per_pixel;
            framebuffer_store_native(
                pixel, (line & (0x80U >> column))
                    ? native_foreground : native_background);
        }
    }
}

// Draw a character at a terminal-cell position.
static void fb_draw_char(char c, int x, int y, uint32_t fg, uint32_t bg) {
    fb_draw_glyph_pixels((uint8_t)c, x * FONT_WIDTH, y * FONT_HEIGHT, fg, bg);
}

