bool framebuffer_fill_rect(int32_t x, int32_t y, uint32_t width,
                           uint32_t height, uint32_t rgb) {
    if (!fb_address) return false;
    if (width == 0 || height == 0) return true;

    int64_t left = x;
    int64_t top = y;
    int64_t right = left + (int64_t)width;
    int64_t bottom = top + (int64_t)height;
    if (left < 0) left = 0;
    if (top < 0) top = 0;
    if (right > (int64_t)fb_width) right = fb_width;
    if (bottom > (int64_t)fb_height) bottom = fb_height;
    if (left >= right || top >= bottom) return true;

    uint32_t native_color = framebuffer_native_color(rgb & 0x00FFFFFFU);
    for (int64_t pixel_y = top; pixel_y < bottom; ++pixel_y) {
        uint8_t *pixel = fb_address + (uint32_t)pixel_y * fb_pitch +
                         (uint32_t)left * fb_bytes_per_pixel;
        if (fb_bytes_per_pixel == sizeof(uint32_t)) {
            uint32_t columns = (uint32_t)(right - left);
            if (fb_shadow_enabled) {
                uint32_t *words = (uint32_t*)pixel;
                for (uint32_t column = 0U; column < columns; ++column)
                    words[column] = native_color;
            } else {
                volatile uint32_t *words = (volatile uint32_t*)pixel;
                for (uint32_t column = 0U; column < columns; ++column)
                    words[column] = native_color;
            }
        } else {
            for (int64_t pixel_x = left; pixel_x < right; ++pixel_x) {
                framebuffer_store_native(pixel, native_color);
                pixel += fb_bytes_per_pixel;
            }
        }
    }
    framebuffer_present_rect((uint32_t)left, (uint32_t)top,
                             (uint32_t)(right - left),
                             (uint32_t)(bottom - top));
    return true;
}

bool framebuffer_write_xrgb8888_span(uint32_t x, uint32_t y,
                                     const uint32_t *pixels, uint32_t count) {
    if (!fb_address || !pixels || count == 0U || y >= fb_height ||
        x >= fb_width || count > fb_width - x) return false;
    uint8_t *destination = fb_address + y * fb_pitch +
                           x * fb_bytes_per_pixel;
    /* VMware SVGA, VBE and the common PC linear framebuffer all expose this
     * native layout.  XRGB8888 can therefore be copied verbatim instead of
     * performing three generic channel conversions for every pixel. */
    if (fb_bytes_per_pixel == sizeof(uint32_t) && fb_red_position == 16U &&
        fb_red_size == 8U && fb_green_position == 8U &&
        fb_green_size == 8U && fb_blue_position == 0U &&
        fb_blue_size == 8U) {
        if (fb_shadow_enabled) {
            memcpy(destination, pixels, (size_t)count * sizeof(uint32_t));
        } else {
            volatile uint32_t *words = (volatile uint32_t*)destination;
            for (uint32_t index = 0U; index < count; ++index)
                words[index] = pixels[index];
        }
        return true;
    }
    for (uint32_t index = 0U; index < count; ++index) {
        framebuffer_store_native(
            destination, framebuffer_native_color(pixels[index]));
        destination += fb_bytes_per_pixel;
    }
    return true;
}

bool framebuffer_present_pixels(uint32_t x, uint32_t y,
                                uint32_t width, uint32_t height) {
    if (!fb_address || width == 0U || height == 0U || x >= fb_width ||
        y >= fb_height || width > fb_width - x || height > fb_height - y)
        return false;
    framebuffer_present_rect(x, y, width, height);
    return true;
}

static bool surface_buffer_block_used(uint32_t block) {
    return (surface_buffer_block_bitmap[block / 32U] &
            (1U << (block % 32U))) != 0U;
}

static void surface_buffer_mark_blocks(uint32_t first_block,
                                       uint32_t block_count,
                                       bool used) {
    for (uint32_t offset = 0U; offset < block_count; ++offset) {
        uint32_t block = first_block + offset;
        uint32_t mask = 1U << (block % 32U);
        if (used)
            surface_buffer_block_bitmap[block / 32U] |= mask;
        else
            surface_buffer_block_bitmap[block / 32U] &= ~mask;
    }
}

static bool surface_buffer_allocate_blocks(uint32_t byte_size,
                                           uint32_t *first_block,
                                           uint32_t *block_count) {
    uint32_t required =
        (byte_size + FB_SURFACE_BUFFER_BLOCK_BYTES - 1U) /
        FB_SURFACE_BUFFER_BLOCK_BYTES;
    if (required == 0U || required > FB_SURFACE_BUFFER_BLOCK_COUNT)
        return false;
    uint32_t run_start = 0U;
    uint32_t run_length = 0U;
    for (uint32_t block = 0U; block < FB_SURFACE_BUFFER_BLOCK_COUNT;
         ++block) {
        if (!surface_buffer_block_used(block)) {
            if (run_length == 0U) run_start = block;
            if (++run_length == required) {
                surface_buffer_mark_blocks(run_start, required, true);
                *first_block = run_start;
                *block_count = required;
                return true;
            }
        } else {
            run_length = 0U;
        }
    }
    return false;
}

static void surface_buffer_release_storage(
    framebuffer_surface_buffer_t *buffer) {
    if (buffer == NULL || buffer->pixels == NULL || buffer->block_count == 0U)
        return;
    surface_buffer_mark_blocks(buffer->first_block, buffer->block_count, false);
    buffer->pixels = NULL;
    buffer->byte_size = 0U;
    buffer->first_block = 0U;
    buffer->block_count = 0U;
    buffer->revoked = false;
}

static void surface_buffer_release_reference(
    framebuffer_surface_buffer_t *buffer) {
    uint32_t flags = spinlock_acquire_irq(&surface_buffer_lock);
    if (buffer != NULL && buffer->references != 0U) --buffer->references;
    if (buffer != NULL && buffer->references == 0U && buffer->revoked &&
        buffer->pixels != NULL)
        surface_buffer_release_storage(buffer);
    spinlock_release_irq(&surface_buffer_lock, flags);
}

int framebuffer_surface_buffer_create(
    int owner_pid, uint32_t owner_generation,
    int consumer_pid, uint32_t consumer_generation,
    uint32_t width, uint32_t height, uint32_t stride_pixels,
    const uint32_t *pixels, uint32_t pixel_count,
    uint32_t *buffer_id, uint32_t *buffer_generation) {
    if (owner_pid <= 0 || owner_generation == 0U || consumer_pid <= 0 ||
        consumer_generation == 0U || width == 0U || height == 0U ||
        width > FB_WIDTH || height > FB_HEIGHT || stride_pixels < width ||
        pixels == NULL || buffer_id == NULL || buffer_generation == NULL ||
        height > UINT32_MAX / stride_pixels ||
        pixel_count != stride_pixels * height ||
        pixel_count > FB_SHADOW_CAPACITY / sizeof(uint32_t)) return -22;
    uint32_t byte_size = pixel_count * sizeof(uint32_t);
    int selected = -1;
    uint32_t first_block = 0U;
    uint32_t block_count = 0U;
    uint32_t flags = spinlock_acquire_irq(&surface_buffer_lock);
    for (uint32_t index = 0U; index < FB_SURFACE_BUFFER_CAPACITY; ++index) {
        if (!surface_buffers[index].active &&
            !surface_buffers[index].constructing &&
            surface_buffers[index].pixels == NULL) {
            selected = (int)index;
            break;
        }
    }
    if (selected >= 0 &&
        surface_buffer_allocate_blocks(byte_size, &first_block,
                                       &block_count)) {
        framebuffer_surface_buffer_t *buffer = &surface_buffers[selected];
        ++buffer->generation;
        if (buffer->generation == 0U) ++buffer->generation;
        buffer->active = false;
        buffer->constructing = true;
        buffer->revoked = false;
        buffer->owner_pid = owner_pid;
        buffer->owner_generation = owner_generation;
        buffer->consumer_pid = consumer_pid;
        buffer->consumer_generation = consumer_generation;
        buffer->width = width;
        buffer->height = height;
        buffer->stride_pixels = stride_pixels;
        buffer->byte_size = byte_size;
        buffer->first_block = first_block;
        buffer->block_count = block_count;
        buffer->references = 0U;
        buffer->pixels = surface_buffer_storage +
            (first_block * FB_SURFACE_BUFFER_BLOCK_BYTES) /
                sizeof(uint32_t);
    } else {
        selected = -1;
    }
    spinlock_release_irq(&surface_buffer_lock, flags);
    if (selected < 0) return -75;
    framebuffer_surface_buffer_t *buffer = &surface_buffers[selected];
    bool valid = true;
    for (uint32_t index = 0U; index < pixel_count; ++index) {
        uint32_t pixel = pixels[index];
        if ((pixel & 0xFF000000U) != 0U) {
            valid = false;
            break;
        }
        buffer->pixels[index] = pixel;
    }
    flags = spinlock_acquire_irq(&surface_buffer_lock);
    if (!valid || buffer->revoked || !buffer->constructing) {
        surface_buffer_release_storage(buffer);
        buffer->active = false;
        buffer->constructing = false;
        spinlock_release_irq(&surface_buffer_lock, flags);
        return valid ? -116 : -22;
    }
    buffer->constructing = false;
    buffer->active = true;
    *buffer_id = (uint32_t)selected + 1U;
    *buffer_generation = buffer->generation;
    spinlock_release_irq(&surface_buffer_lock, flags);
    return 0;
}

int framebuffer_surface_buffer_destroy(
    int owner_pid, uint32_t owner_generation,
    uint32_t buffer_id, uint32_t buffer_generation) {
    if (owner_pid <= 0 || owner_generation == 0U || buffer_id == 0U ||
        buffer_id > FB_SURFACE_BUFFER_CAPACITY ||
        buffer_generation == 0U) return -22;
    uint32_t flags = spinlock_acquire_irq(&surface_buffer_lock);
    framebuffer_surface_buffer_t *buffer = &surface_buffers[buffer_id - 1U];
    if (!buffer->active || buffer->generation != buffer_generation ||
        buffer->owner_pid != owner_pid ||
        buffer->owner_generation != owner_generation) {
        spinlock_release_irq(&surface_buffer_lock, flags);
        return -116;
    }
    buffer->active = false;
    buffer->revoked = true;
    if (buffer->references == 0U) surface_buffer_release_storage(buffer);
    spinlock_release_irq(&surface_buffer_lock, flags);
    return 0;
}

int framebuffer_surface_buffer_draw(
    int consumer_pid, uint32_t consumer_generation,
    int owner_pid, uint32_t owner_generation,
    uint32_t buffer_id, uint32_t buffer_generation,
    uint32_t source_x, uint32_t source_y,
    int32_t destination_x, int32_t destination_y,
    uint32_t width, uint32_t height, uint64_t now_ms) {
    if (!fb_address || consumer_pid <= 0 || consumer_generation == 0U ||
        owner_pid <= 0 || owner_generation == 0U || buffer_id == 0U ||
        buffer_id > FB_SURFACE_BUFFER_CAPACITY ||
        buffer_generation == 0U || destination_x < 0 || destination_y < 0 ||
        width == 0U || height == 0U ||
        (uint32_t)destination_x >= fb_width ||
        (uint32_t)destination_y >= fb_height ||
        width > fb_width - (uint32_t)destination_x ||
        height > fb_height - (uint32_t)destination_y) return -22;

    uint32_t flags = spinlock_acquire_irq(&surface_buffer_lock);
    framebuffer_surface_buffer_t *buffer = &surface_buffers[buffer_id - 1U];
    if (!buffer->active || buffer->generation != buffer_generation ||
        buffer->owner_pid != owner_pid ||
        buffer->owner_generation != owner_generation ||
        buffer->consumer_pid != consumer_pid ||
        buffer->consumer_generation != consumer_generation ||
        source_x >= buffer->width || source_y >= buffer->height ||
        width > buffer->width - source_x ||
        height > buffer->height - source_y || buffer->pixels == NULL) {
        spinlock_release_irq(&surface_buffer_lock, flags);
        return -13;
    }
    ++buffer->references;
    uint32_t *source = buffer->pixels;
    uint32_t stride = buffer->stride_pixels;
    spinlock_release_irq(&surface_buffer_lock, flags);

    int result = framebuffer_frame_draw_enter(
        consumer_pid, consumer_generation, now_ms);
    if (result == 0) {
        for (uint32_t row = 0U; row < height && result == 0; ++row) {
            const uint32_t *span = source +
                (source_y + row) * stride + source_x;
            if (!framebuffer_write_xrgb8888_span(
                    (uint32_t)destination_x,
                    (uint32_t)destination_y + row, span, width))
                result = -19;
        }
        if (result == 0 && !framebuffer_present_pixels(
                (uint32_t)destination_x, (uint32_t)destination_y,
                width, height)) result = -19;
        int leave = framebuffer_frame_draw_leave(
            consumer_pid, consumer_generation, now_ms);
        if (result == 0) result = leave;
    }
    surface_buffer_release_reference(buffer);
    return result;
}

static void framebuffer_surface_buffer_process_cleanup(
    int pid, uint32_t generation) {
    uint32_t flags = spinlock_acquire_irq(&surface_buffer_lock);
    for (uint32_t index = 0U; index < FB_SURFACE_BUFFER_CAPACITY; ++index) {
        framebuffer_surface_buffer_t *buffer = &surface_buffers[index];
        if ((!buffer->active && !buffer->constructing) ||
            !((buffer->owner_pid == pid &&
               buffer->owner_generation == generation) ||
              (buffer->consumer_pid == pid &&
               buffer->consumer_generation == generation))) continue;
        buffer->active = false;
        buffer->revoked = true;
        if (!buffer->constructing && buffer->references == 0U)
            surface_buffer_release_storage(buffer);
    }
    spinlock_release_irq(&surface_buffer_lock, flags);
}

bool framebuffer_draw_text_pixels(int32_t x, int32_t y, const char* text,
                                  size_t length, uint32_t foreground_rgb,
                                  uint32_t background_rgb) {
    if (!fb_address) return false;
    size_t scalar_count = 0U;
    if (!reist_utf8_scan(text, length, &scalar_count)) return false;
    foreground_rgb &= 0x00FFFFFFU;
    background_rgb &= 0x00FFFFFFU;
    size_t source = 0U;
    size_t cell = 0U;
    while (source < length) {
        size_t consumed = 0U;
        uint32_t scalar = 0U;
        if (!reist_utf8_decode_one(text + source, length - source,
                                   &consumed, &scalar)) return false;
        int64_t glyph_x = (int64_t)x + (int64_t)cell * FONT_WIDTH;
        if (glyph_x >= (int64_t)fb_width) break;
        if (glyph_x + FONT_WIDTH <= 0 ||
            (int64_t)y >= (int64_t)fb_height ||
            (int64_t)y + FONT_HEIGHT <= 0) {
            source += consumed;
            ++cell;
            continue;
        }
        fb_draw_glyph_pixels(reist_unicode_vga_glyph(scalar),
                             (int)glyph_x, (int)y, foreground_rgb,
                             background_rgb);
        source += consumed;
        ++cell;
    }
    if (scalar_count != 0U) {
        int64_t left = x < 0 ? 0 : x;
        int64_t top = y < 0 ? 0 : y;
        int64_t right = (int64_t)x + (int64_t)scalar_count * FONT_WIDTH;
        int64_t bottom = (int64_t)y + FONT_HEIGHT;
        if (right > (int64_t)fb_width) right = fb_width;
        if (bottom > (int64_t)fb_height) bottom = fb_height;
        if (left < right && top < bottom)
            framebuffer_present_rect((uint32_t)left, (uint32_t)top,
                                     (uint32_t)(right - left),
                                     (uint32_t)(bottom - top));
    }
    return true;
}

bool framebuffer_draw_text_pixels_clipped(
    int32_t x, int32_t y, const char *text, size_t length,
    uint32_t foreground_rgb, uint32_t background_rgb,
    int32_t clip_x, int32_t clip_y, uint32_t clip_width,
    uint32_t clip_height) {
    if (!fb_address) return false;
    size_t scalar_count = 0U;
    if (!reist_utf8_scan(text, length, &scalar_count)) return false;
    if (length == 0U || clip_width == 0U || clip_height == 0U) return true;

    int64_t left = clip_x;
    int64_t top = clip_y;
    int64_t right = left + clip_width;
    int64_t bottom = top + clip_height;
    if (left < 0) left = 0;
    if (top < 0) top = 0;
    if (right > (int64_t)fb_width) right = fb_width;
    if (bottom > (int64_t)fb_height) bottom = fb_height;
    if (left >= right || top >= bottom) return true;

    foreground_rgb &= 0x00FFFFFFU;
    background_rgb &= 0x00FFFFFFU;
    size_t source = 0U;
    size_t cell = 0U;
    while (source < length) {
        size_t consumed = 0U;
        uint32_t scalar = 0U;
        if (!reist_utf8_decode_one(text + source, length - source,
                                   &consumed, &scalar)) return false;
        int64_t glyph_x = (int64_t)x + (int64_t)cell * FONT_WIDTH;
        int64_t glyph_right = glyph_x + FONT_WIDTH;
        int64_t glyph_top = y;
        int64_t glyph_bottom = glyph_top + FONT_HEIGHT;
        if (glyph_x >= right) break;
        if (glyph_right <= left || glyph_top >= bottom ||
            glyph_bottom <= top) {
            source += consumed;
            ++cell;
            continue;
        }
        fb_draw_glyph_pixels_clipped(
            reist_unicode_vga_glyph(scalar), (int)glyph_x, y,
            foreground_rgb, background_rgb,
            (int)left, (int)top, (int)right, (int)bottom);
        source += consumed;
        ++cell;
    }

    int64_t text_left = x;
    int64_t text_top = y;
    int64_t text_right = text_left + (int64_t)scalar_count * FONT_WIDTH;
    int64_t text_bottom = text_top + FONT_HEIGHT;
    if (text_left < left) text_left = left;
    if (text_top < top) text_top = top;
    if (text_right > right) text_right = right;
    if (text_bottom > bottom) text_bottom = bottom;
    if (text_left < text_right && text_top < text_bottom)
        framebuffer_present_rect(
            (uint32_t)text_left, (uint32_t)text_top,
            (uint32_t)(text_right - text_left),
            (uint32_t)(text_bottom - text_top));
    return true;
}

static void framebuffer_clear_internal(bool present) {
    if (!fb_address) return;
    pointer_visible = false;
    pointer_width = pointer_height = 0U;

    uint32_t native_color = framebuffer_native_color(bg_color);
    for (uint32_t y = 0; y < fb_height; y++) {
        uint8_t *pixel = fb_address + y * fb_pitch;
        if (fb_bytes_per_pixel == sizeof(uint32_t)) {
            if (fb_shadow_enabled) {
                uint32_t *words = (uint32_t*)pixel;
                for (uint32_t x = 0U; x < fb_width; ++x)
                    words[x] = native_color;
            } else {
                volatile uint32_t *words = (volatile uint32_t*)pixel;
                for (uint32_t x = 0U; x < fb_width; ++x)
                    words[x] = native_color;
            }
        } else {
            for (uint32_t x = 0; x < fb_width; x++) {
                framebuffer_store_native(pixel, native_color);
                pixel += fb_bytes_per_pixel;
            }
        }
    }

    cursor_x = 0;
    cursor_y = 0;
    if (present) framebuffer_present_rect(0U, 0U, fb_width, fb_height);
}

// Clear the framebuffer
void framebuffer_clear() {
    framebuffer_clear_internal(true);
}

// Scroll the screen up one line
void framebuffer_scroll() {
    if (!fb_address) return;
    
    if (terminal_rows <= 0 || terminal_cols <= 0) return;
    uint32_t row_bytes = fb_width * fb_bytes_per_pixel;
    uint32_t copy_lines = (uint32_t)(terminal_rows - 1) * FONT_HEIGHT;
    for (uint32_t y = 0; y < copy_lines; ++y) {
        uint8_t *dst = fb_address + y * fb_pitch;
        const uint8_t *src = fb_address + (y + FONT_HEIGHT) * fb_pitch;
        for (uint32_t i = 0; i < row_bytes; ++i) {
            dst[i] = src[i];
        }
    }
    // Clear the last row
    for (int x = 0; x < terminal_cols; x++) {
        fb_draw_char(' ', x, terminal_rows - 1, fg_color, bg_color);
    }
    framebuffer_present_rect(0U, 0U, fb_width, fb_height);
}

// Put a character at current cursor position
void framebuffer_putchar(char c) {
    if (!fb_address) return;

    bool glyph_dirty = false;
    int glyph_x = 0;
    int glyph_y = 0;
    if (c == '\n') {
        cursor_x = 0;
        cursor_y++;
    } else if (c == '\r') {
        cursor_x = 0;
    } else if (c == '\t') {
        cursor_x = (cursor_x + 8) & ~7;
    } else if (c == '\b') {
        if (cursor_x > 0) {
            cursor_x--;
            glyph_x = cursor_x;
            glyph_y = cursor_y;
            fb_draw_char(' ', cursor_x, cursor_y, fg_color, bg_color);
            glyph_dirty = true;
        }
    } else {
        glyph_x = cursor_x;
        glyph_y = cursor_y;
        fb_draw_char(c, cursor_x, cursor_y, fg_color, bg_color);
        glyph_dirty = true;
        cursor_x++;
    }
    
    // Handle line wrap
    if (cursor_x >= terminal_cols) {
        cursor_x = 0;
        cursor_y++;
    }
    
    // Handle scroll
    if (cursor_y >= terminal_rows) {
        framebuffer_scroll();
        cursor_y = terminal_rows - 1;
        glyph_dirty = false;
    }
    if (glyph_dirty)
        framebuffer_present_rect((uint32_t)(glyph_x * FONT_WIDTH),
                                 (uint32_t)(glyph_y * FONT_HEIGHT),
                                 FONT_WIDTH, FONT_HEIGHT);
}

// Write a string
void framebuffer_write_string(const char* str) {
    while (*str) {
        framebuffer_putchar(*str++);
    }
}

// Set foreground and background colors
void framebuffer_set_color(uint32_t fg, uint32_t bg) {
    fg_color = fg;
    bg_color = bg;
}

// Get cursor position
void framebuffer_get_cursor(int* x, int* y) {
    if (x) *x = cursor_x;
    if (y) *y = cursor_y;
}

// Set cursor position
void framebuffer_set_cursor(int x, int y) {
    if (x >= 0 && x < terminal_cols) cursor_x = x;
    if (y >= 0 && y < terminal_rows) cursor_y = y;
}
